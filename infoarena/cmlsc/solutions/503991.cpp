#include<stdio.h>
#define input "cmlsc.in"
#define output "cmlsc.out"
#define N 1031
int n,m,x;
int s[N],t[N],v[N];
int a[N][N];
void open()
{
	freopen(input,"r",stdin);
	freopen(output,"w",stdout);
}
void read()
{
	int i;
	scanf("%d",&n);
	scanf("%d",&m);
	for(i=1;i<=n;i++)
		scanf("%d",&s[i]);
	for(i=1;i<=m;i++)
		scanf("%d",&t[i]);
}
int max(int a,int b)
{
	return (a>b?a:b);
}	
void build()
{
	
	int i,j;
	for(i=1;i<=n;i++)
		for(j=1;j<=m;j++)
		{	
			if(s[i]==t[j])
				a[i][j]=a[i-1][j-1]+1;
			else
				if(s[i]!=t[j])
					a[i][j]=max(a[i-1][j],a[i][j-1]);
		}

}


void write()
{
	int i;
	for(i=x;i>=1;--i)
		printf("%d",v[i]);
}
void trace()
{
	while(n && m)
	{
		if(s[n]==t[m])
		{
			v[++x]=s[n];
			n--;
			m--;
			continue;
		}
		if(max(a[n-1][m],a[n][m-1])==a[n-1][m])
			n--;
		else
			m--;
	}
	write();
}
int main()
{
	open();
	read();
	build();
	printf("%d\n",a[n][m]);
	trace();
	return 0;
}
